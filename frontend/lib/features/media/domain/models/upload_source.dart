/// Источник файла для загрузки.
///
/// Раньше загрузка работала с путём в файловой системе (`dart:io`), но
/// системный пикер на Android отдаёт `content://`-ссылки: файл лежит у
/// провайдера, и читать его можно только потоком.
///
/// Отдельный класс нужен ещё и потому, что системный SAF-пикер без
/// нативной поддержки недоступен: готовые плагины либо копируют файл в
/// кэш целиком (и список появляется через минуту ожидания), либо читают
/// его в память целиком (`file_selector`: `new byte[size]` — на видео в
/// гигабайты это OutOfMemory). Свой пикер отдаёт ссылки сразу, а файл
/// читается потоком — ровно один раз, на заливку.
class UploadSource {
  const new({
    required this.path,
    required this.name,
    required this.openRead,
  });

  /// Идентификатор источника: путь в файловой системе или
  /// `content://`-ссылка. По нему файл опознаётся в списке и в логах.
  final String path;

  /// Имя файла — его сервер увидит в заголовке multipart.
  final String name;

  /// Открывает поток с содержимым файла.
  ///
  /// Каждый вызов — новая попытка: поток читается только один раз.
  final Stream<List<int>> Function() openRead;
}
