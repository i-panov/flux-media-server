export type Language = "ru" | "en";

// Значение из AsyncStorage: всё неизвестное/битое трактуем как «выбора нет»
// и оставляем язык, определённый по системной локали.
export function parseLanguage(
	value: string | null | undefined,
): Language | null {
	return value === "ru" || value === "en" ? value : null;
}

function detectLanguage(): Language {
	try {
		return Intl.DateTimeFormat()
			.resolvedOptions()
			.locale.toLowerCase()
			.startsWith("ru")
			? "ru"
			: "en";
	} catch {
		return "en";
	}
}

let current: Language = detectLanguage();
const listeners = new Set<() => void>();

export function getLanguage(): Language {
	return current;
}

export function setLanguage(language: Language): void {
	if (current === language) {
		return;
	}
	current = language;
	for (const listener of listeners) {
		listener();
	}
}

function subscribe(listener: () => void): () => void {
	listeners.add(listener);
	return () => {
		listeners.delete(listener);
	};
}

// Реактивная подписка для экранов: t() читает модульную переменную,
// а хук заставляет компонент перерисоваться после setLanguage.
export function useLanguage(): Language {
	return useSyncExternalStore(subscribe, getLanguage, getLanguage);
}

export function t(
	key: keyof typeof ru,
	values?: Record<string, string | number>,
): string {
	let text: string = current === "ru" ? ru[key] : en[key];
	if (values !== undefined) {
		for (const [name, value] of Object.entries(values)) {
			text = text.replaceAll(`{{${name}}}`, String(value));
		}
	}
	return text;
}
